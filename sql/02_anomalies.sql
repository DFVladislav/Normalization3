-- ============================================================
-- Шаг 2. Демонстрация трёх аномалий «плохой» таблицы
-- Каждая демонстрация откатывается (ROLLBACK), данные не портятся
-- ============================================================

USE staff_norm;

SET autocommit = 0;

-- ------------------------------------------------------------
-- АНОМАЛИЯ 1: АНОМАЛИЯ ОБНОВЛЕНИЯ (UPDATE ANOMALY)
-- ------------------------------------------------------------
-- Отдел 10 «Отдел реализации» встречается в 4 строках.
-- Чтобы переименовать отдел, придётся обновить ВСЕ эти строки.
-- Если обновить не все — в таблице останутся противоречивые данные.

SELECT COUNT(*) AS rows_of_department_10
FROM employees_bad
WHERE department_id = 10;

-- Придётся обновить сразу 4 строки одним запросом:
UPDATE employees_bad
SET department_name = 'Отдел продаж'
WHERE department_id = 10;

-- А если ошибиться и обновить только часть строк (только один месяц),
-- данные станут ПРОТИВОРЕЧИВЫМИ: у одного отдела два разных названия
UPDATE employees_bad
SET department_name = 'Отдел реализации'
WHERE department_id = 10 AND sales_month = '2026-01-01';

SELECT department_id, department_name, COUNT(*) AS cnt
FROM employees_bad
GROUP BY department_id, department_name;

ROLLBACK;  -- отменяем демо-изменения

-- ------------------------------------------------------------
-- АНОМАЛИЯ 2: АНОМАЛИЯ ВСТАВКИ (INSERT ANOMALY)
-- ------------------------------------------------------------
-- Нельзя добавить НОВЫЙ отдел, пока у него нет ни одного сотрудника
-- с продажами, и нельзя добавить сотрудника без строки продаж:
-- придётся вставлять бессмысленные NULL в несвязанные поля.

-- Попытка завести отдел 40 «Отдел маркетинга» без сотрудников —
-- появляется «висящая» строка-мусор без сотрудника и продаж:
INSERT INTO employees_bad
    (employee_id, employee_name, sales_month, sales,
     department_id, department_name)
VALUES (NULL, NULL, NULL, NULL, 40, 'Отдел маркетинга');

SELECT * FROM employees_bad WHERE department_id = 40;

ROLLBACK;  -- отменяем демо-вставку

-- ------------------------------------------------------------
-- АНОМАЛИЯ 3: АНОМАЛИЯ УДАЛЕНИЯ (DELETE ANOMALY)
-- ------------------------------------------------------------
-- Удалим все строки отдела 20 (единственного сотрудника Сидорову).
-- Вместе с ними НЕОБРАТИМО теряется информация, что вообще
-- существует отдел 20 «Отдел развития».

DELETE FROM employees_bad
WHERE department_id = 20;

-- Строк отдела 20 больше нет:
SELECT * FROM employees_bad WHERE department_id = 20;

-- Информация об отделе 20 исчезла из таблицы полностью:
SELECT DISTINCT department_id, department_name
FROM employees_bad
WHERE department_id = 20;

ROLLBACK;  -- отменяем демо-удаление

-- Возвращаем автокоммит
SET autocommit = 1;

-- Итоговая проверка: данные на месте (ROLLBACK-и всё вернули)
SELECT * FROM employees_bad ORDER BY employee_id, sales_month;
